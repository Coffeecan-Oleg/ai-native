def guide_body():
    paragraphs = guide_text().split('\n\n')
    body = '<h1>Как это работает</h1><section class="panel">'
    for index, paragraph in enumerate(paragraphs):
        if index == 0:
            continue
        title, _, text = paragraph.partition('\n')
        body += '<h2>'+escape(title)+'</h2><p style="white-space:pre-wrap;line-height:1.7">'+escape(text)+'</p>'
    return body + '<p><a href="/platforma/skills">Каталог навыков</a> · <a href="'+KB+'" target="_blank" rel="noopener noreferrer">База знаний</a></p></section>'


def roster_time(value):
    if not value:
        return '—'
    parsed = datetime.fromisoformat(str(value).replace('Z','+00:00'))
    if parsed.tzinfo is None:
        return '—'
    return parsed.astimezone(ZoneInfo('Europe/Moscow')).strftime('%d.%m.%Y %H:%M')


def _table(headers, rows):
    return '<div class="table-wrap"><table><thead><tr>'+''.join('<th>'+escape(h)+'</th>' for h in headers)+'</tr></thead><tbody>'+(''.join('<tr>'+''.join('<td>'+v+'</td>' for v in row)+'</tr>' for row in rows) or '<tr><td colspan="'+str(len(headers))+'">Пока нет успешных входов</td></tr>')+'</tbody></table></div>'


def roster_body(users, query):
    body = '<h1>Сотрудники и входы</h1><p>Только успешные входы через akmetron.bitrix24.ru. Полный штат не импортируется. Время — МСК; «—» означает отсутствие подтверждённого события. Это история входов, а не список сотрудников онлайн.</p>'
    body += '<form method="get"><label>Имя или ID Битрикс24 <input name="q" value="'+escape(query,quote=True)+'" maxlength="200"></label><button>Найти</button></form>'
    rows=[]
    for user in users:
        url='/admin/users/detail?'+urlencode({'subject':user['subject']})
        rows.append(['<a href="'+escape(url,quote=True)+'">'+escape(user.get('login') or user['subject'])+'</a>',
            escape(user.get('bitrix_user_id') or ''),
            *[escape(roster_time(user.get(k))) for k in ('first_login_at','last_panel_login_at','last_mcp_authorization_at','last_mcp_call_at')]])
    return body+_table(['Сотрудник','ID Битрикс24','Первый вход','Вход в панель','Авторизация MCP','Успешный вызов MCP'],rows)


def employee_body(user):
    body = '<h1>'+escape(user.get('login') or 'Сотрудник')+'</h1><p><a href="/admin/users">Все сотрудники и входы</a></p>'
    rows=[[escape(title),escape(roster_time(user.get(key)))] for title,key in (
        ('Первый успешный вход','first_login_at'),('Последний вход в панель','last_panel_login_at'),
        ('Последняя авторизация MCP','last_mcp_authorization_at'),('Последний успешный вызов MCP','last_mcp_call_at'))]
    body += '<p>ID Битрикс24: '+escape(user.get('bitrix_user_id') or '')+'</p>'+_table(['Событие','Время МСК'],rows)
    body += '<p>Базовый доступ определяется действующей внутренней учётной записью и повторно проверяется при обращении. Администрирование и рабочие сервисы разрешаются отдельно. История входов не подтверждает текущий онлайн-статус.</p>'
    if user.get('revoked_at'):
        body += '<p>Сохранённый корпоративный вход отозван; для доступа требуется повторный вход.</p>'
    return body
