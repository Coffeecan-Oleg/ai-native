/* ===========================================================================
   Акметрон — Протокол встречи: РЕДАКТИРУЕМЫЙ СЛОЙ КОНТЕНТА.
   Это ЕДИНСТВЕННЫЙ файл, который меняется под каждую встречу.
   Дизайн и вёрстка (protokol.css + renderer.js) применяются автоматически.

   Разделы (sections) рендерятся СТРОГО в порядке массива. Доступные kind:
     { kind:"agenda",  title, items:[ "пункт", ... ] }
         нумерованная повестка.
     { kind:"topics",  title, items:[ { h, text?, bullets?:[...] }, ... ] }
         обсуждаемые темы; каждый объект — карточка (подзаголовок + проза + список).
     { kind:"decisions", title, groups:[ { owner, role?, tasks:[ {task, due?}, ... ] } ] }
         решения/задачи, сгруппированы по владельцу; due — срок (можно опустить).
     { kind:"list",    title, items:[ "..." ], ordered?:true }
         перечень (итоги, следующие шаги). ordered:false → маркеры вместо цифр.
     { kind:"callout", title, label?, text }
         выделенный блок (например «Следующий шаг»). title не печатается отдельно,
         label — это надпись внутри плашки (по умолчанию «Следующий шаг»).
     { kind:"text",    title, text }
         обычный абзац под заголовком раздела.

   Фото со встречи НЕ описываются здесь — они передаются аргументами в
   render_pdf.py и автоматически добавляются галереей «Материалы со встречи».

   Правила оформления текста — см. SKILL.md (раздел «Грамотность и стиль»).
   =========================================================================== */

